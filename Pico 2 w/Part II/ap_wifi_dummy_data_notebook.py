# pc_udp_test.py

# socket:
#   PC에서 네트워크 통신을 하기 위한 파이썬 표준 모듈
#   여기서는 UDP 통신을 위해 사용한다.
import socket

# time:
#   반복 실행 중 잠깐 대기하기 위해 사용한다.
import time


# ------------------------------------------------------------
# Pico 2 W의 IP 주소와 UDP 포트 번호
# ------------------------------------------------------------

# Pico 2 W가 AP 모드로 동작할 때 보통 자기 IP는 192.168.4.1이다.
# 즉, 노트북은 이 주소로 UDP 데이터를 보낸다.
PICO_IP = "192.168.4.1"

# Pico 쪽 코드에서 UDP 수신용으로 열어 둔 포트 번호이다.
# Pico 코드에도 같은 값이 있어야 한다.
#
# Pico 쪽:
#   PICO_PORT = 5005
PICO_PORT = 5005


# ------------------------------------------------------------
# UDP 소켓 생성
# ------------------------------------------------------------

# UDP 통신용 소켓을 만든다.
#
# socket.AF_INET:
#   IPv4 주소 체계를 사용한다는 뜻
#
# socket.SOCK_DGRAM:
#   UDP 통신을 사용한다는 뜻
#
# UDP는 TCP와 달리 연결 과정이 없다.
# 그래서 connect() 없이 sendto()로 바로 데이터를 보낼 수 있다.
sock = socket.socket(socket.AF_INET, socket.SOCK_DGRAM)


# ------------------------------------------------------------
# 수신 대기 시간 설정
# ------------------------------------------------------------

# recvfrom()은 기본적으로 데이터가 올 때까지 계속 기다린다.
# 그런데 Pico가 응답하지 않으면 프로그램이 멈춘 것처럼 보일 수 있다.
#
# settimeout(2.0)은 최대 2초까지만 기다리라는 뜻이다.
# 2초 안에 응답이 오지 않으면 socket.timeout 예외가 발생한다.
sock.settimeout(2.0)


# ------------------------------------------------------------
# 시작 메시지 출력
# ------------------------------------------------------------

print("UDP test start")

# 현재 PC 코드가 어느 IP와 포트로 데이터를 보내는지 출력한다.
# 여기서는 Pico 2 W의 IP와 포트이다.
print("Target:", PICO_IP, PICO_PORT)


# ------------------------------------------------------------
# UDP 송신 및 수신 반복
# ------------------------------------------------------------

# 계속 반복하면서 Pico에게 HELLO를 보내고 응답을 기다린다.
while True:
    try:
        # ----------------------------------------------------
        # 1. Pico 2 W로 HELLO 메시지 전송
        # ----------------------------------------------------

        # sendto(data, address):
        #   UDP 데이터를 지정한 주소로 보낸다.
        #
        # b"HELLO":
        #   문자열 "HELLO"를 bytes 형태로 표현한 것이다.
        #   UDP로 보낼 때는 문자열이 아니라 bytes 데이터를 보내야 한다.
        #
        # (PICO_IP, PICO_PORT):
        #   데이터를 보낼 대상 주소이다.
        #   예: ("192.168.4.1", 5005)
        sock.sendto(b"HELLO", (PICO_IP, PICO_PORT))

        print("Sent: HELLO")


        # ----------------------------------------------------
        # 2. Pico 2 W의 응답 기다리기
        # ----------------------------------------------------

        # recvfrom(1024):
        #   UDP 데이터를 받을 때 사용한다.
        #
        # 1024:
        #   한 번에 최대 1024바이트까지 받겠다는 뜻이다.
        #
        # 반환값:
        #   data : 받은 데이터 내용, bytes 타입
        #   addr : 보낸 쪽 주소, 예: ('192.168.4.1', 5005)
        #
        # Pico가 정상적으로 응답하면 data에는 b"PICO_OK"가 들어온다.
        data, addr = sock.recvfrom(1024)


        # 받은 데이터는 bytes 타입이므로 decode()로 문자열로 바꿔 출력한다.
        #
        # 예:
        #   data        -> b"PICO_OK"
        #   data.decode() -> "PICO_OK"
        print("Received from", addr, ":", data.decode())


        # ----------------------------------------------------
        # 3. 1초 대기 후 다시 반복
        # ----------------------------------------------------

        # 너무 빠르게 반복하지 않도록 1초 쉰다.
        time.sleep(1)


    except socket.timeout:
        # ----------------------------------------------------
        # Pico 2 W로부터 2초 동안 응답이 없을 때
        # ----------------------------------------------------

        # settimeout(2.0)을 설정했기 때문에
        # 2초 안에 응답이 없으면 여기로 온다.
        #
        # 가능한 원인:
        #   1. 노트북이 PICO2W-OPEN에 접속되어 있지 않음
        #   2. Pico 쪽 UDP 코드가 실행 중이 아님
        #   3. Pico IP가 192.168.4.1이 아님
        #   4. Pico 쪽 포트 번호가 5005가 아님
        #   5. Windows 방화벽이 Python 통신을 막고 있음
        print("No response from Pico")


    except KeyboardInterrupt:
        # ----------------------------------------------------
        # 사용자가 Ctrl + C를 눌러 프로그램을 중지했을 때
        # ----------------------------------------------------

        print("Stopped")

        # while True 반복문을 빠져나간다.
        break


# ------------------------------------------------------------
# 소켓 닫기
# ------------------------------------------------------------

# 프로그램을 끝내기 전에 UDP 소켓을 닫는다.
# 꼭 안 닫아도 프로그램 종료 시 정리되지만,
# 명시적으로 닫는 습관이 좋다.
sock.close()
