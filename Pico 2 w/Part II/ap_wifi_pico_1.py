# main.py

# ------------------------------------------------------------
# 필요한 모듈 가져오기
# ------------------------------------------------------------

# network 모듈:
#   Pico 2 W의 Wi-Fi 기능을 제어하기 위한 모듈이다.
#   AP 모드, STA 모드 설정에 사용한다.
import network

# time 모듈:
#   sleep() 함수를 사용하기 위한 모듈이다.
#   Wi-Fi 상태가 바뀔 때 잠깐 기다리기 위해 사용한다.
import time


# ------------------------------------------------------------
# Pico 2 W가 만들 Wi-Fi 이름 설정
# ------------------------------------------------------------

# SSID는 Wi-Fi 이름이다.
# 노트북의 Wi-Fi 목록에 이 이름이 표시된다.
#
# 예:
#   노트북 Wi-Fi 목록 → PICO2W-OPEN 선택
#
# 여기서는 암호 없는 공개 Wi-Fi로 만들 예정이다.
SSID = "PICO2W-OPEN"


# ------------------------------------------------------------
# STA 모드 끄기
# ------------------------------------------------------------

# STA 모드는 Station 모드의 줄임말이다.
#
# Station 모드란?
#   Pico 2 W가 다른 Wi-Fi 공유기에 접속하는 모드이다.
#
# 예:
#   Pico 2 W  →  집/강의실 공유기(Ria2G)에 접속
#
# 하지만 지금은 Pico 2 W가 직접 Wi-Fi를 만들어야 한다.
# 즉, Pico 2 W를 AP로 사용할 것이다.
#
# 그래서 먼저 STA 모드를 꺼 준다.
sta = network.WLAN(network.WLAN.IF_STA)

# STA 모드 비활성화
# 이전에 다른 공유기에 연결하려던 설정이 남아 있을 수 있으므로
# 확실하게 꺼 주는 것이 좋다.
sta.active(False)

# Wi-Fi 모드가 꺼지는 데 약간의 시간이 필요할 수 있으므로 1초 대기한다.
time.sleep(1)


# ------------------------------------------------------------
# AP 모드 객체 만들기
# ------------------------------------------------------------

# AP 모드는 Access Point 모드의 줄임말이다.
#
# AP 모드란?
#   Pico 2 W가 직접 Wi-Fi 네트워크를 만드는 모드이다.
#
# 예:
#   Pico 2 W가 PICO2W-OPEN 이라는 Wi-Fi를 만든다.
#   노트북은 그 Wi-Fi에 접속한다.
#
# 이때 Pico 2 W는 작은 공유기처럼 동작한다.
ap = network.WLAN(network.WLAN.IF_AP)


# ------------------------------------------------------------
# 기존 AP 상태 초기화
# ------------------------------------------------------------

# 혹시 이전에 AP 모드가 켜져 있었다면 먼저 꺼 준다.
# 기존 설정이 남아 있는 상태에서 새 설정을 적용하면
# 예상과 다르게 동작할 수 있기 때문이다.
ap.active(False)

# AP가 완전히 꺼질 시간을 주기 위해 1초 대기한다.
time.sleep(1)


# ------------------------------------------------------------
# AP 세부 설정
# ------------------------------------------------------------

# ap.config()는 AP 모드의 설정을 지정하는 함수이다.
ap.config(
    # ssid:
    #   노트북 Wi-Fi 목록에 보일 이름이다.
    #   여기서는 PICO2W-OPEN 이라는 Wi-Fi 이름을 만든다.
    ssid=SSID,

    # security:
    #   Wi-Fi 보안 방식을 지정한다.
    #
    #   security=0은 암호가 없는 공개 Wi-Fi를 의미한다.
    #   즉, 노트북에서 비밀번호 없이 접속한다.
    #
    # 참고:
    #   security=0 : 암호 없음, Open
    #   security=3 : WPA2-PSK, 비밀번호 사용
    security=0,

    # channel:
    #   Wi-Fi 채널 번호이다.
    #
    #   Pico 2 W는 2.4GHz Wi-Fi를 사용한다.
    #   2.4GHz에서는 보통 1, 6, 11번 채널을 많이 사용한다.
    #
    #   여기서는 6번 채널을 사용한다.
    channel=6
)


# ------------------------------------------------------------
# AP 모드 켜기
# ------------------------------------------------------------

# 설정이 끝났으므로 AP 모드를 활성화한다.
# 이 코드가 실행되면 노트북 Wi-Fi 목록에
# PICO2W-OPEN이 보이기 시작한다.
ap.active(True)


# ------------------------------------------------------------
# AP가 켜질 때까지 기다리기
# ------------------------------------------------------------

# ap.active()가 True이면 AP 모드가 켜진 상태이다.
#
# AP가 켜지는 데 약간의 시간이 걸릴 수 있으므로
# 완전히 활성화될 때까지 반복해서 확인한다.
while not ap.active():
    time.sleep(0.1)


# ------------------------------------------------------------
# AP 시작 정보 출력
# ------------------------------------------------------------

# Thonny Shell에 AP 시작 메시지를 출력한다.
print("Open Access Point started")

# 현재 Pico 2 W가 만든 Wi-Fi 이름을 출력한다.
print("SSID:", SSID)

# Pico 2 W의 네트워크 정보를 출력한다.
#
# 보통 다음과 비슷하게 출력된다.
#
# ('192.168.4.1', '255.255.255.0', '192.168.4.1', '8.8.8.8')
#
# 의미:
#   첫 번째 값: Pico 2 W 자신의 IP 주소
#   두 번째 값: 서브넷 마스크
#   세 번째 값: 게이트웨이 주소
#   네 번째 값: DNS 주소
#
# AP 모드에서는 보통 Pico 2 W의 IP가 192.168.4.1이다.
print("IP config:", ap.ifconfig())


# ------------------------------------------------------------
# 프로그램 유지
# ------------------------------------------------------------

# 여기서 프로그램이 끝나면 AP 동작도 멈출 수 있다.
# 따라서 while True로 프로그램을 계속 실행 상태로 유지한다.
#
# 이 코드에서는 아직 UDP 통신이나 센서 읽기는 하지 않는다.
# 단지 Pico 2 W가 Wi-Fi AP로 계속 켜져 있게 하는 역할이다.
while True:
    # CPU를 너무 바쁘게 쓰지 않도록 1초마다 한 번씩 쉬게 한다.
    time.sleep(1)
